import { describe, it, expect, beforeEach, afterEach } from "vitest";
import * as fs from "node:fs/promises";
import * as path from "node:path";
import * as os from "node:os";
import { execFile } from "node:child_process";
import { promisify } from "node:util";
import { analyzeRepository } from "../src/analyzer.js";
import { runCli } from "../src/cli.js";
import { verifyTargetWithMutants } from "../src/verify.js";

const execFileAsync = promisify(execFile);

async function git(cwd: string, args: string[]): Promise<string> {
  const { stdout } = await execFileAsync("git", args, { cwd });
  return stdout.trim();
}

describe("Ticket #10 (Ticket 2): Rust end-to-end slice (inline #[cfg(test)] separation, intra-file Git Freshness, cargo-mutants & verify)", () => {
  let tmpDir: string;

  beforeEach(async () => {
    tmpDir = await fs.mkdtemp(path.join(os.tmpdir(), "codefog-t10-rust-"));
    await git(tmpDir, ["init", "-b", "main"]);
    await git(tmpDir, ["config", "user.name", "Test Bot"]);
    await git(tmpDir, ["config", "user.email", "bot@example.com"]);
    await fs.mkdir(path.join(tmpDir, "src"), { recursive: true });
    await fs.mkdir(path.join(tmpDir, "coverage"), { recursive: true });
  });

  afterEach(async () => {
    await fs.rm(tmpDir, { recursive: true, force: true });
  });

  it("strips inline #[cfg(test)] mod tests from production regions/LOC, classifies assert_eq! vs .unwrap()/is_ok() Liveness Checks, and detects intra-file Fog Returned", async () => {
    const rsFile = path.join(tmpDir, "src", "ledger.rs");
    const lcovFile = path.join(tmpDir, "coverage", "lcov.info");

    // Commit 1: Production functions + inline #[cfg(test)] mod tests in the same file
    // - compute_fee (lines 1-6): tested with `assert_eq!` -> `verified`
    // - parse_token (lines 8-13): tested ONLY with `parse_token("abc").unwrap()` and `assert!(parse_token("abc").is_ok())` -> `weak-evidence` (`assertionsOnOutcome: 0`, `pseudoTested: true`)
    // - inline `#[cfg(test)] mod tests` (lines 15-31): must NOT appear in `file.regions` and its lines must NOT inflate production `totalLoc` even if LCOV has DA entries for lines 15-31!
    const commit1Rust = [
      "pub fn compute_fee(amount: i64) -> i64 {",
      "    if amount <= 0 {",
      "        return 0;",
      "    }",
      "    amount * 2",
      "}",
      "",
      "pub fn parse_token(raw: &str) -> Result<usize, &'static str> {",
      "    if raw.is_empty() {",
      '        return Err("empty");',
      "    }",
      "    Ok(raw.len())",
      "}",
      "",
      "#[cfg(test)]",
      "mod tests {",
      "    use super::*;",
      "",
      "    #[test]",
      "    fn test_compute_fee() {",
      "        assert_eq!(compute_fee(0), 0);",
      "        assert_eq!(compute_fee(50), 100);",
      "    }",
      "",
      "    #[test]",
      "    fn test_parse_token_liveness_only() {",
      '        let _ = parse_token("abc").unwrap();',
      '        assert!(parse_token("xyz").is_ok());',
      "    }",
      "}",
    ].join("\n");

    await fs.writeFile(rsFile, commit1Rust, "utf8");

    // LCOV generated by cargo-llvm-cov --lcov (includes DA entries for both production lines AND inline test lines 20-29)
    const lcovContent = [
      "TN:",
      `SF:${rsFile}`,
      "DA:1,2",
      "DA:2,2",
      "DA:3,1",
      "DA:5,1",
      "DA:8,2",
      "DA:9,2",
      "DA:10,1",
      "DA:12,1",
      "DA:20,1",
      "DA:21,1",
      "DA:22,1",
      "DA:26,1",
      "DA:27,1",
      "DA:28,1",
      "end_of_record",
    ].join("\n");
    await fs.writeFile(lcovFile, lcovContent, "utf8");

    await git(tmpDir, ["add", "."]);
    await git(tmpDir, ["commit", "-m", "feat(ledger): initial Rust ledger with inline tests"]);

    // Commit 2: Update inline test comment/assertion so compute_fee isn't single-commit self-proof-fog
    const commit2Rust = commit1Rust.replace(
      "        assert_eq!(compute_fee(50), 100);",
      "        assert_eq!(compute_fee(50), 100);\n        assert_eq!(compute_fee(-5), 0);",
    );
    await fs.writeFile(rsFile, commit2Rust, "utf8");
    await git(tmpDir, ["add", "src/ledger.rs"]);
    await git(tmpDir, ["commit", "-m", "test(ledger): add negative amount test case"]);

    const report1 = await analyzeRepository({ rootDir: tmpDir });
    expect(report1.summary.totalFiles).toBe(1);
    const file1 = report1.files[0]!;
    expect(file1.path).toBe("src/ledger.rs");

    // Inline test functions must be excluded from production regions and production LOC!
    expect(file1.regions.map((r) => r.symbol)).toEqual(["compute_fee", "parse_token"]);
    expect(report1.summary.totalLoc).toBe(8); // Only the 8 DA lines inside compute_fee (4) + parse_token (4), NOT the 6 DA lines inside #[cfg(test)]!

    const feeReg = file1.regions.find((r) => r.symbol === "compute_fee");
    const tokenReg = file1.regions.find((r) => r.symbol === "parse_token");

    expect(feeReg?.state).toBe("verified");
    expect(feeReg?.assertionsOnOutcome).toBeGreaterThanOrEqual(1);
    expect(feeReg?.pseudoTested).toBe(false);

    // parse_token only had `.unwrap()` and `assert!(....is_ok())` -> Liveness Check (`weak-evidence`, 0 outcome assertions, pseudo-tested)
    expect(tokenReg?.state).toBe("weak-evidence");
    expect(tokenReg?.assertionsOnOutcome).toBe(0);
    expect(tokenReg?.pseudoTested).toBe(true);

    // Commit 3: Pure Rustdoc comment edit (`///`) on `compute_fee` -> must NOT trigger Fog Returned
    const commit3Rust = commit2Rust.replace(
      "pub fn compute_fee(amount: i64) -> i64 {",
      "/// Computes transaction fee.\npub fn compute_fee(amount: i64) -> i64 {",
    );
    await fs.writeFile(rsFile, commit3Rust, "utf8");
    await git(tmpDir, ["add", "src/ledger.rs"]);
    await git(tmpDir, ["commit", "-m", "docs(ledger): add rustdoc comment"]);

    const reportAfterDoc = await analyzeRepository({ rootDir: tmpDir });
    const feeAfterDoc = reportAfterDoc.files[0]?.regions.find((r) => r.symbol === "compute_fee");
    expect(feeAfterDoc?.state).toBe("verified");

    // Commit 4: Modify runtime logic of `compute_fee` (`amount * 2` -> `amount * 3`) WITHOUT modifying `#[cfg(test)] mod tests` -> must trigger intra-file Fog Returned!
    const commit4Rust = commit3Rust.replace("    amount * 2", "    amount * 3");
    await fs.writeFile(rsFile, commit4Rust, "utf8");
    await git(tmpDir, ["add", "src/ledger.rs"]);
    await git(tmpDir, ["commit", "-m", "feat(ledger): increase fee multiplier to 3x"]);

    const reportAfterRuntimeEdit = await analyzeRepository({ rootDir: tmpDir });
    const feeAfterEdit = reportAfterRuntimeEdit.files[0]?.regions.find(
      (r) => r.symbol === "compute_fee",
    );
    expect(feeAfterEdit?.state).toBe("fog-returned");
  });

  it("ingests cargo-mutants outcomes.json via --mutation-report and supports `codefog verify <file.rs> --mutants`", async () => {
    const rsFile = path.join(tmpDir, "src", "quota.rs");
    const lcovFile = path.join(tmpDir, "coverage", "lcov.info");
    const outcomesFile = path.join(tmpDir, "outcomes.json");
    const runnerScript = path.join(tmpDir, "run-rust-check.mjs");

    const rustSource = [
      "pub fn within_quota(used: i32) -> bool {",
      "    if used <= 100 {",
      "        return true;",
      "    }",
      "    false",
      "}",
      "",
      "#[cfg(test)]",
      "mod tests {",
      "    use super::*;",
      "    #[test]",
      "    fn test_within_quota() {",
      "        assert_eq!(within_quota(50), true);",
      "    }",
      "}",
    ].join("\n");

    await fs.writeFile(rsFile, rustSource, "utf8");
    await fs.writeFile(
      lcovFile,
      [
        "TN:",
        `SF:${rsFile}`,
        "DA:1,1",
        "DA:2,1",
        "DA:3,1",
        "DA:5,1",
        "end_of_record",
      ].join("\n"),
      "utf8",
    );

    // cargo-mutants `outcomes.json` with 1 Caught, 1 Missed (on line 2), and 1 Unviable (CompileError, ignored)
    const cargoMutantsOutcomes = {
      outcomes: [
        {
          scenario: {
            Mutant: {
              package: "acme-quota",
              file: "src/quota.rs",
              function: { function_name: "within_quota", return_type: "-> bool" },
              span: { start: { line: 2, column: 8 }, end: { line: 2, column: 19 } },
              replacement: "used < 100",
            },
          },
          summary: "Missed",
        },
        {
          scenario: {
            Mutant: {
              package: "acme-quota",
              file: "src/quota.rs",
              function: { function_name: "within_quota", return_type: "-> bool" },
              span: { start: { line: 3, column: 9 }, end: { line: 3, column: 20 } },
              replacement: "return false",
            },
          },
          summary: "Caught",
        },
        {
          scenario: {
            Mutant: {
              package: "acme-quota",
              file: "src/quota.rs",
              function: { function_name: "within_quota", return_type: "-> bool" },
              span: { start: { line: 2, column: 8 }, end: { line: 2, column: 19 } },
              replacement: "uncompilable",
            },
          },
          summary: "Unviable",
        },
      ],
    };
    await fs.writeFile(outcomesFile, JSON.stringify(cargoMutantsOutcomes, null, 2), "utf8");

    await git(tmpDir, ["add", "."]);
    await git(tmpDir, ["commit", "-m", "feat(quota): add Rust quota module"]);

    let cliOut = "";
    await runCli(
      [
        "--root",
        tmpDir,
        "--mutation-report",
        "outcomes.json",
        "--json",
        "--fail-on",
        "none",
      ],
      {
        stdout: (s) => {
          cliOut += s;
        },
        stderr: () => {},
      },
    );

    const parsedReport = JSON.parse(cliOut);
    expect(parsedReport.summary.metrics.mutationScorePct).toBe(50);
    const quotaRegion = parsedReport.files[0].regions.find(
      (r: { symbol: string }) => r.symbol === "within_quota",
    );
    expect(quotaRegion.state).toBe("weak-evidence");
    expect(quotaRegion.survivingMutants).toHaveLength(1);
    expect(quotaRegion.survivingMutants[0].mutated).toBe("used < 100");

    // Simulated rustc + cargo test runner
    await fs.writeFile(
      runnerScript,
      [
        "import * as fs from 'node:fs';",
        "const src = fs.readFileSync('src/quota.rs', 'utf8');",
        "if (src.includes('undefined')) {",
        "  console.error('error[E0425]: cannot find value `undefined` in this scope');",
        "  process.exit(101);",
        "}",
        "let fn;",
        "if (src.includes('used <= 100')) fn = (u) => u <= 100;",
        "else if (src.includes('used < 100')) fn = (u) => u < 100;",
        "else if (src.includes('used > 100')) fn = (u) => u > 100;",
        "else fn = (_u) => false;",
        "if (src.includes('within_quota(50)') && fn(50) !== true) process.exit(1);",
        "if (src.includes('within_quota(100)') && fn(100) !== true) process.exit(1);",
        "if (src.includes('within_quota(101)') && fn(101) !== false) process.exit(1);",
        "process.exit(0);",
      ].join("\n"),
      "utf8",
    );

    // 1. Fails when `used <= 100` -> `used < 100` survives
    const vRes1 = await verifyTargetWithMutants({
      rootDir: tmpDir,
      targetFile: "src/quota.rs",
      mutants: true,
      testCmd: "node run-rust-check.mjs",
      allowSourceChange: true,
    });
    expect(vRes1.passed).toBe(false);
    expect(vRes1.survivingMutants.some((m) => m.mutated.includes("used < 100"))).toBe(true);

    // 2. Add boundary assertions in inline `#[cfg(test)]` -> passes!
    const strengthenedRust = rustSource.replace(
      "        assert_eq!(within_quota(50), true);",
      "        assert_eq!(within_quota(50), true);\n        assert_eq!(within_quota(100), true);\n        assert_eq!(within_quota(101), false);",
    );
    await fs.writeFile(rsFile, strengthenedRust, "utf8");

    const vRes2 = await verifyTargetWithMutants({
      rootDir: tmpDir,
      targetFile: "src/quota.rs",
      mutants: true,
      testCmd: "node run-rust-check.mjs",
      allowSourceChange: true,
    });
    expect(vRes2.passed).toBe(true);
    expect(vRes2.killedMutants).toBeGreaterThanOrEqual(3);
  });
});
